import { chromium, expect } from "@playwright/test";
import { mkdir } from "node:fs/promises";

// Run only with scripts/experience-preview.ts; this creates records in its temporary schema.
await mkdir(".local/experience", { recursive: true });
const browser = await chromium.launch();
const gate = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
const admin = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = [];
for (const page of [gate, admin]) page.on("pageerror", error => errors.push(error.message));
const reason = `浏览器验收现场报修 ${Date.now()}：护栏松动`;

try {
  await gate.goto("http://127.0.0.1:6177/");
  await gate.getByLabel("员工账号").fill("staff01");
  await gate.getByLabel("密码", { exact: true }).fill("123456");
  await gate.getByRole("button", { name: "登录", exact: true }).click();
  await gate.getByRole("button", { name: "报修", exact: true }).first().click();
  await gate.getByRole("button", { name: "发起申报" }).click();
  let dialog = gate.getByRole("dialog");
  await dialog.locator("select").nth(1).selectOption("creek");
  await dialog.getByPlaceholder("描述损坏、风险及现场情况").fill(reason);
  await dialog.getByRole("button", { name: "提交申报" }).click();
  await expect(dialog).toHaveCount(0);
  const request = gate.locator(".gate-workflow__row").filter({ hasText: reason });
  await expect(request).toBeVisible();
  const firstRow = gate.locator(".gate-workflow__row").first();
  await expect(firstRow).toContainText(reason);
  const bounds = await firstRow.boundingBox();
  if (!bounds || bounds.y + bounds.height > 780) throw Error("新申报未完整显示在手机首屏列表中");
  await gate.screenshot({ path: ".local/experience/gate-followup-list.png" });
  await request.click();
  dialog = gate.getByRole("dialog");
  await expect(dialog).toContainText(reason);
  await expect(dialog).toContainText("等待管理员确认");
  await dialog.getByRole("button", { name: "返回列表" }).click();

  await admin.goto("http://127.0.0.1:6179/");
  await admin.locator("#username").fill("admin01");
  await admin.locator("#password").fill("123456");
  await admin.getByRole("button", { name: "登录", exact: true }).click();
  await expect(admin.getByText("工作台", { exact: true }).first()).toBeVisible();
  await admin.goto("http://127.0.0.1:6179/#/oa");
  const approval = admin.locator(".workflow article").filter({ hasText: reason }).filter({ has: admin.getByRole("button", { name: "批准并生成工单" }) });
  await expect(approval).toBeVisible();
  await approval.getByRole("button", { name: "批准并生成工单" }).click();
  let approvalDialog = admin.getByRole("dialog", { name: "设施申请审批" });
  await approvalDialog.getByPlaceholder("说明批准或驳回原因").fill("已核实现场风险，安排维修");
  await approvalDialog.getByRole("button", { name: "确认提交" }).click();
  await expect(approvalDialog).toHaveCount(0);
  await expect(admin.locator(".workflow article").filter({ has: admin.getByText(reason, { exact: true }) }).last()).toContainText("已批准");

  await gate.reload();
  await expect(request).toContainText("已批准");
  await request.click();
  dialog = gate.getByRole("dialog");
  await expect(dialog).toContainText("已生成维修工单");
  await expect(dialog).toContainText("已核实现场风险");
  await dialog.getByRole("button", { name: "查看工单" }).click();
  await expect(dialog).toContainText("待派单");
  await gate.screenshot({ path: ".local/experience/gate-followup-detail.png" });
  await dialog.getByRole("button", { name: "返回列表" }).click();
  await gate.getByRole("tab", { name: /工单进度/ }).click();
  const order = gate.locator(".gate-workflow__row").filter({ hasText: reason });
  await expect(order).toBeVisible();
  const work = admin.locator(".workflow article").filter({ hasText: reason }).filter({ has: admin.getByRole("button", { name: "查看与处理" }) });
  await work.getByRole("button", { name: "查看与处理" }).click();
  let adminDialog = admin.getByRole("dialog");
  await adminDialog.locator("select").selectOption("staff01");
  await adminDialog.getByRole("button", { name: "派单", exact: true }).click();
  await expect(adminDialog).toContainText("待接单");

  await gate.reload();
  await gate.getByRole("tab", { name: /工单进度/ }).click();
  await order.click();
  dialog = gate.getByRole("dialog");
  await dialog.getByRole("button", { name: "接单", exact: true }).click();
  await dialog.getByRole("button", { name: "开始处理" }).click();
  await dialog.getByPlaceholder("填写处理结果或受阻情况").fill("缺少栏杆连接件，暂无法继续维修");
  await dialog.getByRole("button", { name: "受阻反馈" }).click();
  await expect(dialog).toContainText("已挂起");
  await admin.reload();
  await work.getByRole("button", { name: "查看与处理" }).click();
  adminDialog = admin.getByRole("dialog");
  await adminDialog.getByLabel("处理说明").fill("已补充栏杆连接件");
  await adminDialog.getByRole("button", { name: "补充资源" }).click();
  await expect(adminDialog).toContainText("补充资源已保存");
  await adminDialog.getByLabel("处理说明").fill("连接件已送达，恢复处理");
  await adminDialog.getByRole("button", { name: "恢复处理" }).click();
  await expect(adminDialog).toContainText("处理中");
  await gate.reload();
  await gate.getByRole("tab", { name: /工单进度/ }).click();
  await order.click();
  dialog = gate.getByRole("dialog");
  await expect(dialog).toContainText("连接件已送达，恢复处理");
  await dialog.getByPlaceholder("填写处理结果或受阻情况").fill("栏杆连接件已更换，完成现场检查");
  await dialog.getByRole("button", { name: "提交验收" }).click();
  await expect(dialog).toContainText("待验收");

  await admin.reload();
  await work.getByRole("button", { name: "查看与处理" }).click();
  adminDialog = admin.getByRole("dialog");
  await adminDialog.getByLabel("处理说明").fill("复核时仍有松动，请再加固");
  await adminDialog.getByRole("button", { name: "驳回返工" }).click();
  await expect(adminDialog).toContainText("处理中");
  await gate.reload();
  await gate.getByRole("tab", { name: /工单进度/ }).click();
  await order.click();
  dialog = gate.getByRole("dialog");
  await expect(dialog).toContainText("复核时仍有松动，请再加固");
  await dialog.getByPlaceholder("填写处理结果或受阻情况").fill("二次加固完成，复查无松动");
  await dialog.getByRole("button", { name: "提交验收" }).click();
  await admin.reload();
  await work.getByRole("button", { name: "查看与处理" }).click();
  adminDialog = admin.getByRole("dialog");
  await adminDialog.getByLabel("处理说明").fill("复验通过");
  await adminDialog.getByRole("button", { name: "验收通过" }).click();
  await gate.reload();
  await gate.getByRole("tab", { name: /工单进度/ }).click();
  await order.click();
  await expect(gate.getByRole("dialog")).toContainText("已完成");
  await expect(gate.getByRole("dialog")).toContainText("复验通过");
  await gate.screenshot({ path: ".local/experience/gate-followup-complete.png" });
  expect(errors).toEqual([]);
  console.log(JSON.stringify({ passed: true, reason, screenshots: ["gate-followup-list.png", "gate-followup-detail.png"] }));
} catch (error) {
  await gate.screenshot({ path: ".local/experience/gate-followup-failure.png" }).catch(() => {});
  throw error;
} finally {
  await browser.close();
}
