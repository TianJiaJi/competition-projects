import { chromium, expect } from "@playwright/test";
import { mkdir } from "node:fs/promises";

// Run after starting scripts/experience-preview.ts; all writes stay in its temporary schema.
const root = "http://127.0.0.1";
const output = ".local/knowledge-chat";
await mkdir(output, { recursive: true });
const browser = await chromium.launch();
const errors = [];
const failures = [];
const admin = await browser.newPage({ viewport: { width: 1440, height: 900 } });
admin.on("pageerror", (error) => errors.push(error.message));
admin.on("response", (response) => {
  if (response.url().includes("/api/v1/") && response.status() >= 400)
    failures.push(`${response.status()} ${response.url()}`);
});
try {
  await admin.goto(`${root}:6179/`);
  await admin.locator("#username").fill("admin01");
  await admin.locator("#password").fill("123456");
  await admin.getByRole("button", { name: "登录", exact: true }).click();
  await expect(admin.getByText("工作台", { exact: true }).first()).toBeVisible();
  const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
  mobile.on("pageerror", (error) => errors.push(error.message));
  mobile.on("response", (response) => {
    if (response.url().includes("/api/v1/") && response.status() >= 400)
      failures.push(`${response.status()} ${response.url()}`);
  });
  await mobile.goto(`${root}:6176/#/pages/login/index`);
  await mobile.locator("input").nth(0).fill("visitor01");
  await mobile.locator("input[type=password]").fill("123456");
  await mobile.getByText("登录", { exact: true }).click();
  await mobile.waitForURL("**/pages/me/index");
  const knowledgeSources = () => mobile.evaluate(async () => {
    const { request } = await import("/src/services/qa.ts");
    return (await request("/knowledge/sources")).items;
  });
  await admin.goto(`${root}:6179/#/knowledge`);
  await expect(admin.getByRole("heading", { name: "知识库管理" })).toBeVisible();
  await admin.screenshot({ path: `${output}/knowledge-list.png` });
  await admin.getByRole("button", { name: "新增知识" }).click();
  await admin.screenshot({ path: `${output}/knowledge-editor.png` });
  const title = `浏览器知识验收${Date.now()}`;
  const editor = admin.getByRole("dialog");
  await editor.getByLabel("标题").fill(title);
  await editor.getByLabel("关键词（顿号分隔）").fill("验收关键词");
  await editor.getByLabel("正文").fill("浏览器验收正文，测试知识发布和停用后的问答来源。");
  await editor.getByRole("button", { name: "保存草稿" }).click();
  await expect(editor).toHaveCount(0);
  await expect(admin.getByRole("heading", { name: title })).toBeVisible();
  expect((await knowledgeSources()).some(source => source.title.includes(title))).toBe(false);
  await admin.locator(".knowledge-row").filter({ hasText: title }).getByRole("button", { name: "查看 / 编辑" }).click();
  await editor.getByRole("button", { name: "发布到问答" }).click();
  await expect(editor).toHaveCount(0);
  await expect(admin.locator(".knowledge-row").filter({ hasText: title })).toContainText("已发布");
  expect((await knowledgeSources()).some(source => source.title.includes(title))).toBe(true);
  await admin.getByLabel("搜索知识").fill(title);
  await expect(admin.locator(".knowledge-row")).toHaveCount(1);
  await admin.locator(".knowledge-row").getByRole("button", { name: "停用" }).click();
  await expect(admin.locator(".knowledge-row")).toContainText("已停用");
  expect((await knowledgeSources()).some(source => source.title.includes(title))).toBe(false);
  await admin.locator(".knowledge-row").getByRole("button", { name: "查看 / 编辑" }).click();
  await editor.getByRole("button", { name: "发布到问答" }).click();
  await expect(admin.locator(".knowledge-row")).toContainText("已发布");
  expect((await knowledgeSources()).some(source => source.title.includes(title))).toBe(true);
  await admin.locator(".knowledge-row").getByRole("button", { name: "删除" }).click();
  await admin.getByRole("button", { name: "删除", exact: true }).last().click();
  await expect(admin.locator(".knowledge-row")).toHaveCount(0);
  expect((await knowledgeSources()).some(source => source.title.includes(title))).toBe(false);
  await admin.getByLabel("搜索知识").fill("");
  await expect(admin.getByRole("navigation", { name: "知识库分页" })).toBeVisible();
  await admin.getByRole("button", { name: "下一页" }).click();
  await expect(admin.getByRole("navigation", { name: "知识库分页" })).toContainText("第 2 /");
  await admin.setViewportSize({ width: 1366, height: 768 });
  await admin.screenshot({ path: `${output}/knowledge-1366.png` });
  expect(await admin.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth)).toBeLessThanOrEqual(1);
  await admin.setViewportSize({ width: 1440, height: 900 });
  console.log(JSON.stringify({ phase: "knowledge-published", title, errors, failures }));
  await admin.goto(`${root}:6179/#/chat`);
  await admin.getByRole("tab", { name: "房间管控" }).click();
  await expect(admin.getByRole("heading", { name: "房间开放状态" })).toBeVisible();
  await admin.screenshot({ path: `${output}/chat-controls.png` });
  await expect(admin.locator(".chat-control__room").filter({ hasText: "全部聊天室" }).getByRole("button", { name: "全部关闭" })).toBeDisabled();
  await mobile.goto(`${root}:6176/#/pages/chat/index`);
  await expect(mobile.getByText("游客聊天室", { exact: true })).toBeVisible();
  const message = `浏览器聊天验收${Date.now()}`;
  await mobile.locator(".composer input").fill(message);
  await mobile.getByText("发送", { exact: true }).click();
  await expect(mobile.getByText(message, { exact: true }).first()).toBeVisible();
  await admin.reload();
  await admin.getByRole("tab", { name: "房间管控" }).click();
  await expect(admin.locator(".message-choices")).toContainText(message);
  await admin.getByRole("tab", { name: "房间消息" }).click();
  await expect(admin.locator(".message-list")).toContainText(message);
  await admin.getByRole("tab", { name: "房间管控" }).click();
  await admin.screenshot({ path: `${output}/chat-with-message.png` });
  console.log(JSON.stringify({ phase: "chat-message", message, errors, failures }));
  await admin.getByLabel("操作原因").fill("浏览器验收撤回");
  await admin.locator(".message-choices label").filter({ hasText: message }).locator("input").check();
  await admin.getByRole("button", { name: "批量撤回" }).click();
  await expect(admin.locator(".message-choices label").filter({ hasText: message })).toContainText("已撤回");
  await admin.locator(".message-choices label").filter({ hasText: message }).locator("input").check();
  await admin.getByRole("button", { name: "批量恢复" }).click();
  await expect(admin.locator(".message-choices label").filter({ hasText: message })).not.toContainText("已撤回");
  await admin.locator(".message-choices label").filter({ hasText: message }).locator("input").check();
  await admin.getByRole("button", { name: "禁言所选作者" }).click();
  await expect(admin.getByRole("status").filter({ hasText: "已禁言" })).toBeVisible();
  await admin.getByRole("tab", { name: "禁言", exact: true }).click();
  await expect(admin.locator(".data-table")).toContainText("王雨晴");
  await admin.locator(".data-table tr").filter({ hasText: "王雨晴" }).getByRole("button", { name: "解除" }).click();
  await admin.getByRole("button", { name: "解除禁言" }).click();
  await admin.getByRole("tab", { name: "房间管控" }).click();
  await admin.getByLabel("操作原因").fill("浏览器验收关房");
  await admin.locator(".chat-control__room").filter({ hasText: "山间茶叙" }).getByRole("button", { name: "关闭房间" }).click();
  await expect(admin.locator(".chat-control__room").filter({ hasText: "山间茶叙" }).getByRole("button", { name: "重新开放" })).toBeVisible();
  await mobile.reload();
  await expect(mobile.locator("body")).not.toContainText("山间茶叙");
  await admin.locator(".chat-control__room").filter({ hasText: "山间茶叙" }).getByRole("button", { name: "重新开放" }).click();
  await expect(admin.locator(".chat-control__room").filter({ hasText: "山间茶叙" }).getByRole("button", { name: "关闭房间" })).toBeVisible();
  await admin.locator(".chat-control__room").filter({ hasText: "全部聊天室" }).getByRole("button", { name: "全部关闭" }).click();
  await expect(admin.locator(".chat-control__room").filter({ hasText: "全部聊天室" })).toContainText("已关闭");
  await expect(admin.locator(".chat-control__room").filter({ hasText: "山间茶叙" })).toContainText("全局关闭中");
  await admin.locator(".chat-control__room").filter({ hasText: "全部聊天室" }).getByRole("button", { name: "重新开放" }).click();
  await admin.setViewportSize({ width: 1366, height: 768 });
  await admin.screenshot({ path: `${output}/chat-1366.png` });
  const overflow = await admin.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth);
  expect(overflow).toBeLessThanOrEqual(1);
  console.log(JSON.stringify({ phase: "chat-actions", overflow, errors, failures }));
  expect(errors).toEqual([]);
  expect(failures).toEqual([]);
} catch (error) {
  await admin.screenshot({ path: `${output}/failure.png` }).catch(() => {});
  throw error;
} finally {
  await browser.close();
}
