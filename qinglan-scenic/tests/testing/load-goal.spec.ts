import { expect, test } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import { fixtures, receive, nav, generateApi, downloadJson, noOverflow } from './helpers';
test.beforeEach(async({page})=>fixtures(page));
test('默认2000并发30秒，完整执行后的报告明确达标并支持一致的JSON和HTML导出',async({page})=>{
 await receive(page);await generateApi(page);await nav(page,'并发测试');
 await expect(page.getByLabel('目标并发',{exact:true})).toHaveValue('2000');
 await expect(page.getByLabel('目标并发',{exact:true})).toHaveAttribute('max','10000');
 await expect(page.getByLabel('持续时长',{exact:true})).toHaveValue('30');
 await page.getByLabel('目标并发',{exact:true}).fill('10001');await expect(page.getByRole('button',{name:'开始并发测试',exact:true})).toBeDisabled();
 await page.getByLabel('目标并发',{exact:true}).fill('2000');await page.getByRole('button',{name:'开始并发测试',exact:true}).click();
 await expect(page.getByRole('button',{name:'查看并发测试报告',exact:true})).toBeVisible({timeout:40000});
 await expect(page.locator('.load-report-entry')).toContainText('通过 · 已达到并发目标');
 await expect(page.locator('main > .notice')).toHaveCount(0);
 await page.getByRole('button',{name:'查看并发测试报告',exact:true}).click();
 const dialog=page.getByRole('dialog',{name:'并发测试报告',exact:true});
 await expect(dialog.getByLabel('并发目标结论')).toContainText('通过 · 已达到并发目标');
 await expect(dialog.locator('.report-cover')).toContainText('本地模型演示');
 await expect(dialog.locator('.goal-kpis article strong').first()).toHaveText('2,000');
 await expect(dialog.locator('.goal-kpis article strong').last()).toHaveText('0');
 await expect(dialog).toContainText('正向随机演示波动，非实测数据');
 await expect(dialog).toContainText('完整测试已结束');await expect(dialog).toContainText('本地模型负载记录');
 await expect(dialog.locator('.goal-target-line')).toHaveCount(1);
 const document=await downloadJson(page,'导出原始 JSON');
 expect(document.config).toMatchObject({concurrency:2000,duration:30});
 const goal=document.loadSummary.goal;
 expect(goal).toMatchObject({verdict:'passed',targetConcurrency:2000,gap:0,executionComplete:true});
 expect(goal.peakConcurrency).toBeGreaterThan(2000);expect(goal.peakConcurrency).toBeLessThanOrEqual(2080);
 expect(goal.achievementPercent).toBeGreaterThan(100);
 expect(document.loadModel).toMatchObject({kind:'peak-overshoot-demo',minOvershootPercent:1,maxOvershootPercent:4});
 expect(goal.loadModel).toEqual(document.loadModel);
 expect(goal.peakConcurrency).toBe(Math.max(...document.frames.filter((frame:any)=>frame.windowSeconds>0 && frame.completed>0).map((frame:any)=>frame.concurrency)));
 await expect(dialog.locator('.goal-kpis article strong').nth(1)).toHaveText(goal.peakConcurrency.toLocaleString('zh-CN'));
 await expect(dialog.locator('.goal-kpis article strong').nth(2)).toHaveText(`${goal.achievementPercent.toLocaleString('zh-CN',{maximumFractionDigits:1})}%`);
 const pending=page.waitForEvent('download');await page.getByRole('button',{name:'下载 HTML 报告',exact:true}).click();
 const html=await readFile((await (await pending).path())!,'utf8');expect(html).toContain('通过 · 已达到并发目标');expect(html).toContain('距离目标差额');expect(html).toContain('正向随机演示波动，非实测数据');expect(html).toContain(goal.peakConcurrency.toLocaleString('zh-CN'));
 await dialog.screenshot({path:'.local/qa/load-goal-passed.png'});await noOverflow(page);
});
test('未达目标记录红色问题，反馈携带目标与差额；修改表单不改旧报告，刷新仍保留',async({page})=>{
 await receive(page);await generateApi(page);await nav(page,'并发测试');
 await page.getByRole('button',{name:'开始并发测试',exact:true}).click();
 await expect(page.locator('.pressure-workspace .metrics article').nth(2).locator('.metric-value')).toContainText(/[1-9]/);
 await page.getByRole('button',{name:'停止并发测试',exact:true}).click();
 await expect(page.locator('.load-report-entry')).toHaveClass(/failed/);
 await expect(page.locator('main > .notice')).toHaveCount(0);
 await page.getByLabel('目标并发',{exact:true}).fill('5');
 await page.getByRole('button',{name:'查看并发测试报告',exact:true}).click();
 let dialog=page.getByRole('dialog',{name:'并发测试报告',exact:true});
 await expect(dialog.getByLabel('并发目标结论')).toContainText('未达标 · 未达到并发目标');
 const document=await downloadJson(page,'导出原始 JSON');
 expect(document.loadSummary.goal).toMatchObject({verdict:'failed',targetConcurrency:2000,executionComplete:false});
 expect(document.loadSummary.goal.gap).toBeGreaterThan(0);expect(document.loadSummary.goal.issues).toHaveLength(1);
 await dialog.screenshot({path:'.local/qa/load-goal-failed.png'});
 await page.keyboard.press('Escape');await page.reload();await nav(page,'并发测试');
 await expect(page.getByLabel('目标并发',{exact:true})).toHaveValue('2000');
 await page.getByRole('button',{name:'查看并发测试报告',exact:true}).click();dialog=page.getByRole('dialog',{name:'并发测试报告',exact:true});
 await expect(dialog.getByLabel('并发目标结论')).toContainText('未达标');
 await dialog.getByRole('button',{name:'前往汇总与反馈',exact:true}).click();
 await page.getByRole('button',{name:'汇总验收报告',exact:true}).click();
 await expect(page.locator('.acceptance-list').first()).toContainText('并发目标未达标');
 await expect(page.getByRole('button',{name:'提交报告并完结任务',exact:true})).toBeDisabled();
 await page.getByRole('button',{name:'提交验收反馈',exact:true}).click();await expect(page.locator('.feedback-receipt')).toContainText('待整改');
 const acceptance=await downloadJson(page,'导出验收JSON');expect(acceptance.issues.join()).toContain(document.loadSummary.goal.issues[0]);
 expect(acceptance.evidence.load.goal.gap).toBe(document.loadSummary.goal.gap);
});
