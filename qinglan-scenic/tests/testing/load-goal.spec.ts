import { expect, test } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import { fixtures, receive, nav, generateApi, downloadJson, noOverflow } from './helpers';
test.beforeEach(async({page})=>fixtures(page));
test('功能级目标1000与安全上限2000分离，承载1400–1600与图表报告一致',async({page})=>{
 await receive(page);await generateApi(page);await nav(page,'并发测试');
 await expect(page.getByLabel('预期并发目标',{exact:true})).toHaveValue('1000');
 await expect(page.getByLabel('安全加压上限',{exact:true})).toHaveValue('2000');
 await expect(page.getByLabel('预期并发目标',{exact:true})).toHaveAttribute('max','10000');
 await expect(page.getByLabel('持续时长',{exact:true})).toHaveValue('30');
 await page.getByLabel('预期并发目标',{exact:true}).fill('10001');await expect(page.getByRole('button',{name:'开始并发测试',exact:true})).toBeDisabled();
 await page.getByLabel('预期并发目标',{exact:true}).fill('1000');
 await page.getByLabel('安全加压上限',{exact:true}).fill('1500');await expect(page.getByRole('button',{name:'开始并发测试',exact:true})).toBeDisabled();
 await page.getByLabel('安全加压上限',{exact:true}).fill('2000');
 await page.getByLabel('持续时长',{exact:true}).fill('10');
 await expect(page.getByRole('button',{name:'并发测试业务操作',exact:true})).toContainText('查询教室可用时段');
 await expect(page.locator('.pressure-config')).toContainText('预期并发目标');
 // 数据来源在报告中核验，主配置区无需重复展示。
 await expect(page.locator('.context-strip')).not.toContainText('5606');
 await page.getByRole('button',{name:'开始并发测试',exact:true}).click();
 await expect(page.getByRole('button',{name:'查看并发测试报告',exact:true})).toBeVisible({timeout:20000});
 await expect(page.locator('.load-report-entry')).toContainText('通过 · 已达到并发目标');
 await expect(page.locator('.load-goal-strip')).toContainText('稳定承载');
 await expect(page.locator('main > .notice')).toHaveCount(0);
 await page.screenshot({path:'.local/qa/load-capacity-workspace.png',fullPage:true});
 await page.getByRole('button',{name:'查看并发测试报告',exact:true}).click();
 const dialog=page.getByRole('dialog',{name:'并发测试报告',exact:true});
 await expect(dialog.getByLabel('并发目标结论')).toContainText('通过 · 已达到并发目标');
 await expect(dialog.locator('.report-cover')).toContainText('查询教室可用时段');
 await expect(dialog.locator('.goal-kpis article strong').first()).toHaveText('1,000');
 await expect(dialog).toContainText('上下随机浮动100');
 await expect(dialog).toContainText('完整测试已结束');await expect(dialog).toContainText('数据来源：本地模型');
 await expect(dialog.locator('.goal-target-line')).toHaveCount(1);
 const document=await downloadJson(page,'导出原始 JSON');
 expect(document.config).toMatchObject({concurrency:1000,maxConcurrency:2000,duration:10});
 const goal=document.loadSummary.goal;
 expect(goal).toMatchObject({verdict:'passed',targetConcurrency:1000,gap:0,executionComplete:true});
 expect(goal.capacityConcurrency).toBeGreaterThanOrEqual(1400);expect(goal.capacityConcurrency).toBeLessThanOrEqual(1600);
 expect(goal.capacityConcurrency%10).not.toBe(0);
 expect(goal.capacityConcurrency).toBe(goal.peakConcurrency);
 expect(goal.headroom).toBe(goal.capacityConcurrency-1000);
 expect(document.loadModel).toMatchObject({kind:'capacity-demo',offset:500,variation:100,capacity:goal.capacityConcurrency});
 expect(goal.loadModel).toEqual(document.loadModel);
 expect(goal.peakConcurrency).toBe(Math.max(...document.frames.filter((frame:any)=>frame.windowSeconds>0 && frame.completed>0).map((frame:any)=>frame.concurrency)));
 await expect(dialog.locator('.goal-kpis article strong').nth(1)).toHaveText(goal.capacityConcurrency.toLocaleString('zh-CN'));
 await expect(dialog.locator('.goal-kpis article strong').nth(2)).toHaveText(`${goal.achievementPercent.toLocaleString('zh-CN',{maximumFractionDigits:1})}%`);
 await expect(dialog.locator('.goal-kpis article strong').last()).toHaveText(goal.headroom.toLocaleString('zh-CN'));
 const pending=page.waitForEvent('download');await page.getByRole('button',{name:'下载 HTML 报告',exact:true}).click();
 const html=await readFile((await (await pending).path())!,'utf8');expect(html).toContain('通过 · 已达到并发目标');expect(html).toContain('超出目标');expect(html).toContain('数据来源：本地模型');expect(html).toContain(goal.capacityConcurrency.toLocaleString('zh-CN'));
 await dialog.screenshot({path:'.local/qa/load-capacity-report.png'});await noOverflow(page);
 await page.keyboard.press('Escape');
 await page.getByLabel('预期并发目标',{exact:true}).fill('500');
 await expect(page.getByLabel('安全加压上限',{exact:true})).toHaveValue('1500');
 await page.getByRole('button',{name:'查看并发测试报告',exact:true}).click();
 await expect(dialog.locator('.goal-kpis article strong').first()).toHaveText('1,000');
 await page.keyboard.press('Escape');await page.reload();await nav(page,'并发测试');
 await expect(page.locator('.load-goal-strip')).toContainText(goal.capacityConcurrency.toLocaleString('zh-CN'));
});
test('提前停止保留待补测，刷新不丢失，也不把预设容量自动判为通过',async({page})=>{
 await receive(page);await generateApi(page);await nav(page,'并发测试');
 await page.getByRole('button',{name:'开始并发测试',exact:true}).click();
 await expect(page.locator('.pressure-workspace .metrics article').nth(2).locator('.metric-value')).toContainText(/[1-9]/);
 await page.getByRole('button',{name:'停止并发测试',exact:true}).click();
 await expect(page.locator('.load-report-entry')).toHaveClass(/insufficient/);
 await page.getByRole('button',{name:'查看并发测试报告',exact:true}).click();
 let dialog=page.getByRole('dialog',{name:'并发测试报告',exact:true});
 await expect(dialog.getByLabel('并发目标结论')).toContainText('待补测');
 const document=await downloadJson(page,'导出原始 JSON');
 expect(document.loadSummary.goal).toMatchObject({verdict:'insufficient',targetConcurrency:1000,capacityConcurrency:0,executionComplete:false});
 await page.keyboard.press('Escape');await page.reload();await nav(page,'并发测试');
 await page.getByRole('button',{name:'查看并发测试报告',exact:true}).click();dialog=page.getByRole('dialog',{name:'并发测试报告',exact:true});
 await expect(dialog.getByLabel('并发目标结论')).toContainText('待补测');
 await page.keyboard.press('Escape');await nav(page,'验收报告');
 await page.getByRole('button',{name:'汇总验收报告',exact:true}).click();
 await expect(page.getByRole('button',{name:'提交报告并完结任务',exact:true})).toBeDisabled();
 await page.getByRole('button',{name:'提交验收反馈',exact:true}).click();await expect(page.locator('.feedback-receipt')).toContainText('待补测');
 const acceptance=await downloadJson(page,'导出验收JSON');expect(acceptance.evidence.load.goal.verdict).toBe('insufficient');
});
