import { expect, test } from '@playwright/test';
import { fixtures, receive, nav, downloadJson, noOverflow } from './helpers';
import { API_CASE_COUNT } from '../../apps/testing/src/campus-handoff';
test.beforeEach(async({page})=>fixtures(page));
test('默认参数、推荐导航顺序及开始测试入口',async({page})=>{
 await receive(page);
 await expect(page.locator('main > .notice')).toHaveCount(0);
 await expect(page.locator('.workbench-header').getByRole('button',{name:'开始测试',exact:true})).toBeVisible();
 await expect(page.locator('main [aria-label="测试任务流程"]')).toHaveCount(0);
 await expect(page.getByText('本轮测试流程',{exact:true})).toHaveCount(0);
 await page.getByRole('button',{name:'开始测试',exact:true}).click();
 await expect(page.getByRole('navigation',{name:'测试工作台导航'}).getByRole('button',{name:/^UI测试/})).toHaveAttribute('aria-current','page');
 const navigation=await page.getByRole('navigation',{name:'测试工作台导航'}).innerText();
 expect(navigation.indexOf('并发测试')).toBeLessThan(navigation.indexOf('专项测试'));
 await nav(page,'并发测试');
 await expect(page.getByLabel('目标并发',{exact:true})).toHaveValue('2000');
 await expect(page.getByLabel('持续时长',{exact:true})).toHaveValue('30');
 await expect(page.getByRole('button',{name:'开始并发测试',exact:true})).toBeDisabled();
 await noOverflow(page);
 await nav(page,'API测试');
 for(const width of [1920,1440,1100,900,390]){
   await page.setViewportSize({width,height:1000});await noOverflow(page);
   await expect(page.locator('main .workflow-guide,main .header-test-navigation')).toHaveCount(0);
   await expect(page.locator('.workbench-header')).toHaveCSS('height',width<=700?'62px':'72px');
   if(width===1440 || width===390)await page.screenshot({path:`.local/qa/header-test-navigation-${width}.png`,fullPage:true});
 }
});
test('API结束后手动打开报告、刷新恢复、从记录重开并前往下一项',async({page})=>{
 await receive(page);await nav(page,'API测试');
 await expect(page.getByRole('button',{name:'查看API测试报告',exact:true})).toHaveCount(0);
 await page.getByRole('button',{name:'解析API材料',exact:true}).click();
 await expect(page.getByRole('button',{name:'材料已解析',exact:true})).toBeDisabled();
 await page.getByRole('button',{name:'生成测试用例',exact:true}).click();
 await expect(page.locator('.api-table tbody tr')).toHaveCount(API_CASE_COUNT);
 await page.getByRole('button',{name:'运行全部API',exact:true}).click();
 await expect(page.getByRole('button',{name:'查看API测试报告',exact:true})).toBeVisible({timeout:20000});
 await expect(page.getByRole('dialog',{name:'API测试报告',exact:true})).toHaveCount(0);
 await page.getByRole('button',{name:'查看API测试报告',exact:true}).click();
 const dialog=page.getByRole('dialog',{name:'API测试报告',exact:true});
 await expect(dialog).toContainText('不发送真实业务测试请求');
 const report=await downloadJson(page,'导出API原始JSON');
 expect(report.samples).toHaveLength(API_CASE_COUNT);
 await dialog.getByRole('button',{name:'返回测试工作区',exact:true}).click();
 await page.reload();await nav(page,'API测试');
 await expect(page.getByRole('button',{name:'查看API测试报告',exact:true})).toBeEnabled();
 const completedApi=page.getByRole('group',{name:'测试阶段切换'}).getByRole('button',{name:/^API测试/});
 await expect(completedApi).toHaveClass(/done/);
 await expect(completedApi).toHaveCSS('background-color','rgb(213, 233, 216)');
 await page.locator('.workbench-header').getByRole('button',{name:'下一项：并发测试',exact:true}).click();
 await expect(completedApi).toHaveCSS('background-color','rgb(220, 238, 221)');
 await expect(completedApi).toHaveCSS('border-top-color','rgb(184, 213, 187)');
 await expect(page.getByRole('group',{name:'测试阶段切换'}).getByRole('button',{name:/^并发测试/})).not.toHaveClass(/done/);
 await expect(page.getByLabel('目标并发',{exact:true})).toHaveValue('2000');
 await expect(page.getByRole('button',{name:'开始并发测试',exact:true})).toBeEnabled();
 await nav(page,'验收报告');await page.getByRole('button',{name:'查看报告',exact:true}).click();
 await expect(dialog).toBeVisible();
});
test('提交后无重复完成提示，归档入口保留在顶栏且不恢复工作记录',async({page})=>{
 await receive(page);await nav(page,'UI测试');
 await page.getByRole('button',{name:'一键完成五端检查',exact:true}).click();
 await expect(page.getByRole('button',{name:'查看报告',exact:true})).toBeVisible();
 await nav(page,'API测试');
 await page.getByRole('button',{name:'解析API材料',exact:true}).click();
 await expect(page.getByRole('button',{name:'材料已解析',exact:true})).toBeDisabled();
 await page.getByRole('button',{name:'生成测试用例',exact:true}).click();
 await expect(page.locator('.api-table tbody tr')).toHaveCount(API_CASE_COUNT);
 await page.getByRole('button',{name:'运行全部API',exact:true}).click();
 await expect(page.getByRole('button',{name:'查看API测试报告',exact:true})).toBeVisible({timeout:20000});
 await nav(page,'并发测试');await page.getByLabel('持续时长',{exact:true}).fill('10');
 await page.getByRole('button',{name:'开始并发测试',exact:true}).click();
 await expect(page.getByRole('button',{name:'查看并发测试报告',exact:true})).toBeVisible({timeout:20000});
 await nav(page,'专项测试');await page.getByRole('button',{name:'生成专项用例',exact:true}).click();
 await expect(page.getByRole('button',{name:'一键测试',exact:true})).toBeEnabled();
 await page.getByRole('button',{name:'一键测试',exact:true}).click();
 await expect(page.locator('.special-run-panel .badge.good')).toHaveText('已完成',{timeout:20000});
 await nav(page,'验收报告');await page.getByRole('button',{name:'汇总验收报告',exact:true}).click();
 await page.getByRole('button',{name:'提交报告并完结任务',exact:true}).click();
 const confirmation=page.getByRole('dialog',{name:'提交报告并完结任务',exact:true});
 await confirmation.getByRole('checkbox').check();await confirmation.getByRole('button',{name:'确认提交并完结',exact:true}).click();
 await expect(page.getByRole('button',{name:'查看验收报告',exact:true})).toBeVisible();
 await expect(page.locator('main > .notice')).toHaveCount(0);
 await nav(page,'UI测试');
 await expect(page.locator('main > .notice')).toHaveCount(0);
 await expect(page.locator('.workbench-header .header-test-navigation')).toHaveCount(0);
 await page.locator('.workbench-header').getByRole('button',{name:'查看已归档报告',exact:true}).click();
 await expect(page.locator('.task-completion-receipt')).toBeVisible();
 await expect(page.locator('main > .notice')).toHaveCount(0);
 await page.locator('.workbench-header').getByRole('button',{name:'返回任务中心',exact:true}).click();
 await nav(page,'API测试');await expect(page.locator('.api-table tbody tr')).toHaveCount(0);
});
