"""Regenerate the static, seamless terrain paths; requires numpy and contourpy.
No generation or numerical libraries run in the browser.
"""
from pathlib import Path
import json
import numpy as np
import contourpy

WIDTH, HEIGHT = 1600, 1120
x = np.linspace(0, WIDTH, 641)
y = np.linspace(0, HEIGHT, 449)
u, v = np.meshgrid(x * (2 * np.pi / WIDTH), y * (2 * np.pi / HEIGHT))
# A periodic height field with warped ridges, shelves and saddles. All contour
# levels sample the SAME field: distances change with slope, without crossings.
a = u + .38 * np.sin(v + .5) + .17 * np.sin(2 * v - u)
b = v + .32 * np.sin(u - .8) + .13 * np.cos(2 * u + v)
z = (.70 * np.sin(a + .3) + .55 * np.cos(2 * b - .2)
     + .25 * np.sin(2 * a + b + 1.2) + .13 * np.cos(3 * a - 2 * b + .7)
     + .055 * np.sin(5 * u + 3 * v + .4) + .03 * np.cos(7 * u - 4 * v))
# Skip the summit/depression extremes, so no repeated bullseye peaks dominate.
levels = np.arange(-1.05, 1.10, .155)
cg = contourpy.contour_generator(x=x, y=y, z=z, name='serial')
def simplify(points, tolerance=.3):
    if len(points) < 3:
        return points
    start, end = points[0], points[-1]
    segment = end - start
    length = np.linalg.norm(segment)
    distances = (np.abs(segment[0] * (start[1] - points[:, 1])
                        - (start[0] - points[:, 0]) * segment[1]) / length
                 if length else np.linalg.norm(points - start, axis=1))
    split = int(np.argmax(distances))
    if distances[split] <= tolerance:
        return points[[0, -1]]
    return np.vstack((simplify(points[:split + 1], tolerance)[:-1],
                      simplify(points[split:], tolerance)))

paths = []
for level in levels:
    pieces = []
    for points in cg.lines(float(level)):
        if len(points) < 8:
            continue
        # Simplify within 0.3px; keep border endpoints and avoid spline overshoot.
        closed = np.linalg.norm(points[0] - points[-1]) < .001
        points = simplify(points)
        pieces.append('M' + ' L'.join(f'{px:.1f} {py:.1f}' for px, py in points) + (' Z' if closed else ''))
    paths.append(' '.join(pieces))
out = Path(__file__).resolve().parents[1] / 'terrain.ts'
out.write_text('// Generated by scripts/generate-terrain.py. Static periodic height-field contours.\n'
               + f'export const terrainWidth = {WIDTH};\nexport const terrainHeight = {HEIGHT};\n'
               + 'export const terrainPaths = ' + json.dumps(paths, indent=2) + ';\n')
print(f'{len(levels)} elevations, {sum(len(p) for p in paths)} SVG path bytes → {out}')
